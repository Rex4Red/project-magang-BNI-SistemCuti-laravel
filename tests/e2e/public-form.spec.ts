import {test,expect} from '@playwright/test';
import {addDays,addMonths,blockedDays,isWorking} from '../../shared/domain';

test.skip(process.env.CUTI_PUBLIC_FORM!=='true','Alur formulir publik diuji dengan CUTI_PUBLIC_FORM=true.');
const display=(iso:string)=>iso.split('-').reverse().join('/');

test('pemohon langsung tercatat tanpa approval dan admin memonitor data cuti',async({page,browser},testInfo)=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Pengajuan cuti',exact:true})).toBeVisible();
  await expect(page.getByLabel('Kata sandi',{exact:true})).toHaveCount(0);
  await page.getByLabel('Nama lengkap',{exact:true}).fill('Pemohon Form Publik');
  await expect(page.getByLabel('Email',{exact:true})).toHaveCount(0);
  await expect(page.getByLabel('Nomor HP',{exact:true})).toHaveCount(0);
  await expect(page.getByLabel('NPP',{exact:true})).not.toHaveAttribute('placeholder');
  await page.getByLabel('NPP',{exact:true}).fill('P123456');
  const config=await (await page.request.get('/api/public/form')).json();
  const unit=config.units[0];
  await page.getByLabel('Outlet',{exact:true}).selectOption(unit.outlets[0].id);
  await page.getByLabel('Posisi',{exact:true}).selectOption('BMB');
  await page.getByLabel('Jenis cuti',{exact:true}).fill('Keperluan keluarga');
  await page.getByLabel('Alasan pengajuan',{exact:true}).fill('Pengujian pengajuan tanpa membuat akun.');
  let start=addMonths(config.today,1);
  while(!isWorking(start,unit.calendar)||blockedDays(start.slice(0,7),unit.calendar).includes(start))start=addDays(start,1);
  await page.getByLabel('Tanggal mulai',{exact:true}).fill(display(start));
  await expect(page.getByLabel('Tanggal akhir',{exact:true})).toHaveValue('');
  await expect(page.getByRole('button',{name:'Kirim pengajuan',exact:true})).toBeDisabled();
  await page.getByLabel('Tanggal akhir',{exact:true}).fill(display(start));
  await page.getByLabel('Tanggal mulai',{exact:true}).clear();
  await expect(page.getByLabel('Tanggal akhir',{exact:true})).toHaveValue('');
  await page.getByLabel('Tanggal mulai',{exact:true}).fill(display(start));
  await page.getByLabel('Tanggal akhir',{exact:true}).fill(display(start));
  await page.keyboard.press('Escape');await page.getByLabel('Alasan pengajuan',{exact:true}).click();
  await expect(page.getByRole('button',{name:'Kirim pengajuan',exact:true})).toBeEnabled();
  expect(await page.locator('.public-sheet form').evaluate((form:HTMLFormElement)=>form.checkValidity())).toBe(true);
  await expect(page.locator('.public-duration')).toContainText('1 hari kerja');
  await page.screenshot({path:testInfo.outputPath('public-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:testInfo.outputPath('public-mobile.png'),fullPage:true});
  await page.getByRole('button',{name:'Kirim pengajuan',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Cuti berhasil dicatat'})).toBeVisible();
  await expect(page.locator('.public-success')).toContainText('Tercatat');
  await expect(page.locator('.public-success')).not.toContainText('Menunggu review');
  const number=await page.locator('.public-success dd strong').innerText();
  expect((await page.request.get('/api/me')).status()).toBe(401);
  await page.screenshot({path:testInfo.outputPath('public-receipt.png'),fullPage:true});
  await page.getByRole('button',{name:'Buat pengajuan lain'}).click();
  await expect(page.getByLabel('Alasan pengajuan',{exact:true})).toHaveValue('');

  const adminContext=await browser.newContext();const admin=await adminContext.newPage();
  await admin.goto('/');await admin.getByRole('link',{name:'Masuk admin',exact:true}).click();
  await expect(admin.locator('.demo-accounts')).toHaveCount(0);
  await admin.screenshot({path:testInfo.outputPath('admin-login.png'),fullPage:true});
  await admin.getByLabel('Email admin',{exact:true}).fill('admin@demo.bni.local');
  await admin.getByLabel('Kata sandi',{exact:true}).fill('BniCuti!2026');
  await admin.getByRole('button',{name:'Masuk',exact:true}).click();
  await expect(admin.getByRole('heading',{name:'Ringkasan',exact:true})).toBeVisible();
  const popup=admin.getByRole('dialog',{name:'Pengajuan menunggu review'});
  await expect(popup).toHaveCount(0);
  await expect(admin.locator('.stats-grid')).toContainText('Cuti tercatat');
  await expect(admin.locator('.stats-grid')).not.toContainText('Menunggu review');
  await expect(admin.locator('.stats-grid')).not.toContainText('Disetujui');
  await admin.screenshot({path:testInfo.outputPath('admin-records-desktop.png'),fullPage:true,animations:'disabled'});
  await admin.setViewportSize({width:390,height:844});
  await expect.poll(()=>admin.locator('.sidebar').evaluate(element=>element.getBoundingClientRect().right<=0)).toBe(true);
  await expect(admin.locator('.requests-panel .badge.recorded').first()).toBeInViewport();
  expect(await admin.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await admin.screenshot({path:testInfo.outputPath('admin-records-mobile.png'),fullPage:true,animations:'disabled'});
  await admin.setViewportSize({width:1280,height:900});
  await admin.locator('nav').getByRole('button',{name:/Pengajuan cuti/}).click();
  await expect(admin.getByRole('button',{name:'Disetujui',exact:true})).toHaveCount(0);
  await expect(admin.getByRole('button',{name:'Perlu Batal',exact:true})).toHaveCount(0);
  await admin.getByLabel('Cari pengajuan').fill(number);
  await admin.getByRole('button',{name:'Lihat Pemohon Form Publik '+number,exact:true}).click();
  await expect(admin.getByRole('dialog').getByText('Tercatat',{exact:true})).toBeVisible();
  await expect(admin.getByRole('button',{name:/Setujui pengajuan|Tolak pengajuan|Jadi mengambil cuti|Konfirmasi keputusan/})).toHaveCount(0);
  await admin.getByRole('button',{name:'Bukti pencatatan',exact:true}).click();
  await expect(admin.locator('.certificate-modal')).toContainText('BUKTI PENCATATAN CUTI');
  await expect(admin.locator('.certificate-modal')).not.toContainText('DISETUJUI');
  await admin.locator('.certificate-modal').getByRole('button',{name:'Tutup',exact:true}).click();
  await admin.getByRole('button',{name:'Tutup dialog',exact:true}).click();
  await admin.locator('nav').getByRole('button',{name:'Kalender cuti',exact:true}).click();
  await admin.getByLabel('Bulan monitoring').fill(start.slice(0,7));
  await expect(admin.locator('.calendar-event').filter({hasText:'Pemohon Form Publik'}).first()).toContainText('Tercatat');
  await admin.getByRole('tab',{name:'Rekap bulanan',exact:true}).click();
  const rekapRow=admin.locator('.leave-summary-table tbody tr').filter({hasText:'Pemohon Form Publik'});
  await expect(rekapRow).toContainText('P123456');
  await expect(rekapRow.locator('.summary-approved').first()).toBeVisible();
  await expect(admin.locator('.summary-legend')).toContainText('Tercatat');
  const downloadPromise=admin.waitForEvent('download');
  await admin.getByRole('link',{name:'Ekspor Excel',exact:true}).click();
  expect((await downloadPromise).suggestedFilename()).toBe('rekap-kalender-cuti-'+start.slice(0,7)+'.xlsx');
  const verification=await admin.request.get('/api/verify-certificate?num='+encodeURIComponent(number));
  expect(await verification.json()).toMatchObject({valid:true,recordOnly:true,status:'RECORDED'});
  await admin.locator('nav').getByRole('button',{name:'Administrasi',exact:true}).click();
  const adminTabs=admin.locator('.list-toolbar .tabs').getByRole('button');
  await expect(adminTabs).toHaveText(['Posisi','Outlet','Posisi & kuota']);
  await expect(admin.getByRole('heading',{name:'Master posisi',exact:true})).toBeVisible();
  await adminTabs.getByText('Outlet',{exact:true}).click();
  await expect(admin.getByRole('heading',{name:'Outlet cabang',exact:true})).toBeVisible();
  await expect(admin.getByText('Atur outlet, lalu tempatkan karyawan melalui menu Karyawan.')).toHaveCount(0);
  await adminTabs.getByText('Posisi & kuota',{exact:true}).click();
  await expect(admin.getByRole('heading',{name:'Kuota orang per posisi',exact:true})).toBeVisible();
  await admin.reload();
  await expect(admin.getByRole('heading',{name:'Kuota orang per posisi',exact:true})).toBeVisible();
  for(const removedTab of ['employees','jobs']){
    await admin.evaluate(tab=>sessionStorage.setItem('bni_cuti_admin_tab',tab),removedTab);
    await admin.reload();
    await expect(admin.getByRole('heading',{name:'Master posisi',exact:true})).toBeVisible();
    await expect(adminTabs).toHaveText(['Posisi','Outlet','Posisi & kuota']);
  }
  await admin.screenshot({path:testInfo.outputPath('admin-settings-desktop.png'),fullPage:true,animations:'disabled'});
  await admin.setViewportSize({width:390,height:844});
  expect(await admin.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await admin.screenshot({path:testInfo.outputPath('admin-settings-mobile.png'),fullPage:true,animations:'disabled'});
  await admin.setViewportSize({width:1280,height:900});
  await admin.getByRole('button',{name:'Profil saya',exact:true}).click();
  await admin.getByRole('button',{name:'Keluar dari akun',exact:true}).click();
  await expect(admin.getByRole('heading',{name:'Pengajuan cuti',exact:true})).toBeVisible();
  await page.goto('/#verify?num='+encodeURIComponent(number));
  await expect(page.getByText('TERCATAT',{exact:true})).toBeVisible();
  await expect(page.getByText('Status Persetujuan:',{exact:true})).toHaveCount(0);
  expect(errors).toEqual([]);await adminContext.close();
});

test('gagal memuat formulir menampilkan tombol coba lagi',async({page})=>{
  await page.route('**/api/public/form',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({message:'Formulir sementara tidak tersedia.'})}));
  await page.goto('/');
  await expect(page.getByRole('alert')).toContainText('Formulir sementara tidak tersedia.');
  await page.unroute('**/api/public/form');
  await page.getByRole('button',{name:'Coba lagi',exact:true}).click();
  await expect(page.getByLabel('Nama lengkap',{exact:true})).toBeVisible();
});

test('kalender publik memblokir H-3, mendukung keyboard, dan login bisa dibatalkan',async({page})=>{
  await page.goto('/');const config=await (await page.request.get('/api/public/form')).json();
  await page.getByLabel('Outlet',{exact:true}).selectOption(config.units[0].outlets[0].id);
  await page.getByLabel('Tanggal mulai',{exact:true}).click();
  const picker=page.getByRole('dialog',{name:'Pilih Tanggal mulai',exact:true});
  const month=addMonths(config.today,1).slice(0,7);
  for(const date of blockedDays(month,config.units[0].calendar))await expect(picker.getByRole('button',{name:String(Number(date.slice(-2))),exact:true})).toBeDisabled();
  await page.keyboard.press('Escape');await expect(picker).toHaveCount(0);
  await page.getByLabel('Darurat',{exact:true}).check();
  await expect(page.getByText('Cuti darurat tidak perlu menunggu satu bulan.',{exact:false})).toBeVisible();
  await page.getByRole('link',{name:'Masuk admin',exact:true}).click();
  await expect(page.getByLabel('Email admin',{exact:true})).toBeVisible();
  await page.getByRole('link',{name:'Kembali ke formulir cuti'}).click();
  await expect(page.getByRole('heading',{name:'Pengajuan cuti',exact:true})).toBeVisible();
});
